def _workbook(data: bytes):
    from openpyxl import load_workbook

    return load_workbook(io.BytesIO(data))


def _fmt(kind: str, value) -> str:
    """The test's OWN formatter (never the module's): money 2 dp, rate 4 dp,
    litres 3 dp — the scales `contract_audit` quantized to."""
    dec = Decimal(str(value))
    if kind == "money":
        return f"{dec:,.2f}"
    if kind == "rate":
        return f"{dec:.4f}"
    return f"{dec:,.3f}"


_SHARED_KINDS = ("text", "text", "text", "text", "qty", "text", "rate", "rate", "rate", "money")


def _shared_rows(data: bytes) -> list[list[str]]:
    """The packet's shared demand block (the first 10 columns of `Evidence`),
    as display strings — the same values the letter prints."""
    ws = _workbook(data)[overcharge_pack.PACKET_SHEET_EVIDENCE]
    rows = list(ws.iter_rows(values_only=True))
    out: list[list[str]] = []
    for row in rows[1:]:
        if row[0] in (None, "", overcharge_pack.TOTAL_LABEL):
            break
        out.append(
            [
                str(row[i]) if _SHARED_KINDS[i] == "text" else _fmt(_SHARED_KINDS[i], row[i])
                for i in range(10)
            ]
        )
    return out


def _packet_total(data: bytes) -> Decimal:
    ws = _workbook(data)[overcharge_pack.PACKET_SHEET_EVIDENCE]
    for row in ws.iter_rows(values_only=True):
        if row[0] == overcharge_pack.TOTAL_LABEL:
            return Decimal(str(row[9]))
    raise AssertionError("the evidence sheet has no TOTAL row")


def _code_only(module) -> str:
    """A module's CODE with every docstring removed (AST round-trip) — so a
    structural scan asserts on what the module DOES, not on what its prose says
    it must never do."""
    import ast

    tree = ast.parse(inspect.getsource(module))
    for node in ast.walk(tree):
        if isinstance(node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
            body = node.body
            if (
                body
                and isinstance(body[0], ast.Expr)
                and isinstance(body[0].value, ast.Constant)
                and isinstance(body[0].value.value, str)
            ):
                node.body = body[1:] or [ast.Pass()]
    return ast.unparse(tree)


def _pdf_text(data: bytes) -> str:
    from pypdf import PdfReader

    text = "".join(p.extract_text() or "" for p in PdfReader(io.BytesIO(data)).pages)
    return re.sub(r"\s+", " ", text)


def _assert_in_order(text: str, values: list[str]) -> None:
    """Every value appears, in this order — so the letter prints a ROW, not a
    coincidental scatter of matching substrings."""
    cursor = 0
    for value in values:
        idx = text.find(value, cursor)
        assert idx >= 0, f"{value!r} missing from the letter after position {cursor}"
        cursor = idx + len(value)


