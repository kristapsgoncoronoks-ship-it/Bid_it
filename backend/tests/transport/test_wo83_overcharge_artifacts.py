async def test_wo83_mixed_currency_lines_total_in_eur_and_never_sum_a_local_amount(db_session):
    """§4.14 — a supplier month spanning EUR and PLN produces ONE EUR total
    equal to the hand-computed Decimal sum; the PLN line's own currency is
    printed as provenance and never totalled."""
    org, entity = await _org(db_session)
    await contract_audit.set_term(
        db_session,
        org.id,
        supplier=SUPPLIER,
        country="LV",
        product_group="Diesel",
        expected_discount_eur_l=Decimal("0.20"),
    )
    await _txn(db_session, org.id, entity.id, line_seq=1)  # EUR -> 150.00
    await _txn(
        db_session,
        org.id,
        entity.id,
        line_seq=2,
        currency="PLN",
        qty=Decimal("2000.000"),
        net_eur=Decimal("2600.00"),
        net_eur_eff=Decimal("2400.00"),
    )  # -> 200.00
    claim = await overcharge.open_claim(db_session, org.id, supplier=SUPPLIER, period=PERIOD)

    data = await overcharge_pack.build_evidence_packet(db_session, org.id, claim.id)

    assert _packet_total(data) == Decimal("350.00")
    ws = _workbook(data)[overcharge_pack.PACKET_SHEET_EVIDENCE]
    rows = list(ws.iter_rows(values_only=True))
    currencies = [rows[1][13], rows[2][13]]
    assert sorted(currencies) == ["EUR", "PLN"]
    header = {
        r[0]: r[1]
        for r in _workbook(data)[overcharge_pack.PACKET_SHEET_CLAIM].iter_rows(values_only=True)
    }
    assert header["Currency"] == "EUR"


async def test_wo83_generating_both_artifacts_mutates_nothing_and_audits_nothing(db_session):
    """R41 "read-only over the analytics" / §4.19: after building BOTH
    artifacts the claim-back and every fuel-transaction column are identical and
    no audit row was written."""
    org, entity = await _org(db_session)
    claim = await _claim(db_session, org.id, entity.id)
    await db_session.commit()

    def snapshot(obj, columns):
        return {c: getattr(obj, c) for c in columns}

    claim_cols = (
        "supplier",
        "period",
        "status",
        "detected_eur",
        "recovered_eur",
        "lines_count",
        "note",
    )
    txn_cols = tuple(c.name for c in FuelTransaction.__table__.columns)

    before_claim = snapshot(claim, claim_cols)
    before_txns = [
        snapshot(t, txn_cols)
        for t in await db_session.scalars(
            select(FuelTransaction).where(FuelTransaction.org_id == org.id)
        )
    ]
    before_audit = await db_session.scalar(
        select(func.count()).select_from(AuditEvent).where(AuditEvent.org_id == org.id)
    )

    await overcharge_pack.build_evidence_packet(db_session, org.id, claim.id)
    await overcharge_pack.build_claim_letter(db_session, org.id, claim.id)

    await db_session.refresh(claim)
    assert snapshot(claim, claim_cols) == before_claim
    after_txns = [
        snapshot(t, txn_cols)
        for t in await db_session.scalars(
            select(FuelTransaction).where(FuelTransaction.org_id == org.id)
        )
    ]
    assert after_txns == before_txns
    after_audit = await db_session.scalar(
        select(func.count()).select_from(AuditEvent).where(AuditEvent.org_id == org.id)
    )
    assert after_audit == before_audit
