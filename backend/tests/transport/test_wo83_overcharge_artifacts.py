    """§4.9 / §4.14 — Decimal only, EUR only. The three document-currency amount
    columns are never read; a line's currency rides the packet as PROVENANCE."""
    # Docstrings are stripped first: this module's prose legitimately QUOTES
    # the things the code must not do ("No float anywhere", "never
